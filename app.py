    if METRICS_PATH.exists():
        metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
        st.write(f"**Selected model:** {metrics['selected_model']}")
        st.caption("Metrics are generated by train_model.py from a held-out test split. Re-run training to reproduce them.")
        print("COMPARISON DATA:", metrics["comparison"])
        print("COLUMNS:", pd.DataFrame(metrics["comparison"]).columns.tolist())
